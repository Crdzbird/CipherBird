#!/usr/bin/env python3
"""Writes lib/src/engine_integrity.dart for a Dart package: the sha384
Subresource Integrity digest of every web engine file under assets/, so the
loader, the worker bootstrap and web_setup check the bytes they load against
the bytes that were built and attested. Usage: gen_integrity.py <package-dir>
"""
import base64
import hashlib
import pathlib
import sys

FILES = [
    ('engine', 'cipherbird.js'),
    ('wasm', 'cipherbird.wasm'),
    ('worker', 'cipherbird_worker.js'),
    ('boot', 'cipherbird_boot.js'),
]


def digest(path):
    return 'sha384-' + base64.b64encode(hashlib.sha384(path.read_bytes()).digest()).decode()


def main():
    package = pathlib.Path(sys.argv[1])
    lines = [
        '/// Subresource Integrity digests of the web engine files under assets/,',
        '/// generated by scripts/web/gen_integrity.py from the committed bytes.',
        '/// Every load of an engine file, by the page tags, the loader and the',
        '/// worker bootstrap, is checked against these. Regenerate after a',
        '/// rebuild; do not edit.',
        'final class EngineIntegrity {',
        '  const EngineIntegrity._();',
        '',
    ]
    for name, file in FILES:
        lines += ['  /// Digest of `%s`.' % file,
                  "  static const String %s =\n      '%s';" % (name, digest(package / 'assets' / file)),
                  '']
    lines[-1:] = ['}', '']
    out = package / 'lib' / 'src' / 'engine_integrity.dart'
    out.write_text('\n'.join(lines))
    print('wrote %s' % out)


if __name__ == '__main__':
    main()
