#!/usr/bin/env python3
"""Writes the common-schema token vectors under tests/vectors/tokens/
(docs/TOKEN_API.md, "Vectors") from their sources:

  tests/vectors/paseto/v4.json      the official PASETO v4 vectors (ISC),
                                    of which the v4.local cases are taken
  tests/vectors/cb1/vectors.json    the cb1 vectors cryptolib_tests writes
                                    with CRYPTOLIB_CB1_WRITE_VECTORS=1

Every binding runs one loop over tests/vectors/tokens/<format>.json and
accepts each case through the generic token calls. Run this after
regenerating the cb1 vectors or updating the PASETO ones:

  python3 scripts/tokens/convert_vectors.py
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
OUT = os.path.join(ROOT, "tests", "vectors", "tokens")
LOCAL_KEYS = ["name", "expect-fail", "key", "nonce", "token", "payload", "footer", "implicit-assertion"]
PUBLIC_KEYS = ["name", "expect-fail", "public-key", "secret-key", "token", "payload", "footer", "implicit-assertion"]


def case(src, keys):
    out = {}
    for k in keys:
        v = src.get(k)
        if k == "expect-fail":
            out[k] = bool(v)
        else:
            out[k] = v if v is not None else ""
    return out


def dump(name, fmt, note, cases):
    path = os.path.join(OUT, name + ".json")
    with open(path, "w") as f:
        f.write('{\n  "format": %s,\n  "note": %s,\n  "cases": [\n' % (json.dumps(fmt), json.dumps(note)))
        f.write(",\n".join("    " + json.dumps(c, ensure_ascii=True) for c in cases))
        f.write("\n  ]\n}\n")
    print("%s: %d cases, %d expect-fail" % (name, len(cases), sum(1 for c in cases if c["expect-fail"])))


def main():
    os.makedirs(OUT, exist_ok=True)
    with open(os.path.join(ROOT, "tests", "vectors", "paseto", "v4.json")) as f:
        v4 = json.load(f)
    local = [t for t in v4["tests"] if t.get("token", "").startswith("v4.local.")]
    dump("v4.local", "v4.local",
         "The v4.local cases of the official PASETO test vectors (paseto-standard/test-vectors, ISC license, "
         "see tests/vectors/paseto/LICENSE) in the common token-vector schema; a case without a key is a failure case.",
         [case(t, LOCAL_KEYS) for t in local])
    with open(os.path.join(ROOT, "tests", "vectors", "cb1", "vectors.json")) as f:
        cb1 = json.load(f)
    dump("cb1.local", "cb1.local",
         "Generated by cryptolib_tests (CRYPTOLIB_CB1_WRITE_VECTORS) from docs/CB1_TOKEN.md with a fixed key and "
         "nonce; every binding accepts these.",
         [case(t, LOCAL_KEYS) for t in cb1["local"]])
    dump("cb1.public", "cb1.public",
         "Generated by cryptolib_tests (CRYPTOLIB_CB1_WRITE_VECTORS) from docs/CB1_TOKEN.md with a fixed hybrid "
         "key pair; every binding accepts these.",
         [case(t, PUBLIC_KEYS) for t in cb1["public"]])
    return 0


if __name__ == "__main__":
    sys.exit(main())
